package main

import "fmt"

func main(){
	fmt.Println("go" + "lang") // golang
	
	fmt.Println("2 + 3 = ", 2 + 3)
	fmt.Println("10 / 5 = ", 10/5)
	fmt.Println("10.0 / 5.0 = ", 10.0/5.0)
	fmt.Println("10.0 / 5 = ", 10.0/5)
	fmt.Println("10 / 5.0 = ", 10.0/5)

	fmt.Println(true && false)
	fmt.Println(true || false)
	fmt.Println(!false)
}